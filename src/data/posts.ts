/** Essays dated after the build day stay hidden until a build on or after their date. */
const buildDay = new Date(__BUILD_TIME__).toISOString().slice(0, 10);
export const posts: Post[] = allPosts.filter((post) => post.datePublished <= buildDay);

export const getPost = (slug: string | undefined) => posts.find((post) => post.slug === slug);

export const getPostsByPillar = (pillar: PillarSlug) => posts.filter((post) => post.pillar === pillar);

const WORDS_PER_MINUTE = 220;

export const readingMinutes = (post: Pick<Post, "content">) => {
  const words = textParagraphs(post).join(" ").split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / WORDS_PER_MINUTE));
};

export const readingTime = (post: Pick<Post, "content">) => `${readingMinutes(post)} min read`;

/** Same-pillar essays first, then the most recent others, never the post itself. */
export const getRelatedPosts = (post: Post, count = 2) => {
  const others = posts.filter((p) => p.slug !== post.slug);
  const samePillar = post.pillar ? others.filter((p) => p.pillar === post.pillar) : [];
  const rest = others.filter((p) => !samePillar.includes(p));
  return [...samePillar, ...rest].slice(0, count);
};

/**
 * The essay to read next: the next older one on the same topic (after the oldest, back to that topic's newest),
 * or the next older essay overall when the post has no topic or is the only one in it.
 */
export const getNextPost = (post: Post) => {
  const sameTopic = post.pillar ? posts.filter((p) => p.pillar === post.pillar) : [];
  const list = sameTopic.length > 1 ? sameTopic : posts;
  return list[(list.indexOf(post) + 1) % list.length];
};
