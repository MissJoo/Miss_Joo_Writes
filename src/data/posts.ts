export const getPost = (slug: string | undefined) => posts.find((post) => post.slug === slug);

export const getPostsByPillar = (pillar: PillarSlug) => posts.filter((post) => post.pillar === pillar);

const WORDS_PER_MINUTE = 220;

export const readingMinutes = (post: Pick<Post, "content">) => {
  const words = post.content.join(" ").split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / WORDS_PER_MINUTE));
};

export const readingTime = (post: Pick<Post, "content">) => `${readingMinutes(post)} min read`;

/** Same-pillar essays first, then the most recent others, never the post itself. */
export const getRelatedPosts = (post: Post, count = 2) => {
  const others = posts.filter((p) => p.slug !== post.slug);
  const samePillar = others.filter((p) => p.pillar === post.pillar);
  const rest = others.filter((p) => p.pillar !== post.pillar);
  return [...samePillar, ...rest].slice(0, count);
};
